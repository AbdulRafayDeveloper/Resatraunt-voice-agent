export function getRestaurant(slug: string): Restaurant {
  const restaurant = restaurants.find((r) => r.slug === slug);
  if (!restaurant) throw new Error(`Unknown restaurant: ${slug}`);
  return restaurant;
}

export function findRestaurant(slug: string): Restaurant | undefined {
  return restaurants.find((r) => r.slug === slug);
}

export function restaurantsInCity(citySlug: string): Restaurant[] {
  return restaurants.filter((r) => r.citySlug === citySlug);
}

export function restaurantsForOccasion(occasion: Occasion): Restaurant[] {
  return restaurants.filter((r) => r.occasions.includes(occasion));
}

